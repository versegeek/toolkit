// Package main is the example application entry point.
//
// It demonstrates two lifecycle patterns provided by toolkit.
//
// ── Pattern A: Container (manual, no Wire) ───────────────────────────────────
//
//	c := container.New()
//	c.MustInit(zaplog.New(nil))  // log first — subsequent Init logs use it
//	c.MustInit(redis.New(nil))
//	defer c.MustClose()          // LIFO: redis closed first, then log
//	c.MustRun()                  // blocks until SIGINT / SIGTERM
//
// ── Pattern B: Wire + HandleSignals (current default) ────────────────────────
//
//	app, cleanup, err := InitApp()   // generated by Wire in wire_gen.go
//	defer cleanup()
//	container.HandleSignals(cleanup) // blocks until SIGINT / SIGTERM
package main

import (
	"github.com/versegeek/toolkit/container"
	"go.uber.org/zap"
)

func main() {
	// Pattern B — Wire-generated InitApp + HandleSignals.
	// To switch to Pattern A, replace this block with the Container example above.
	app, cleanup, err := InitApp()
	if err != nil {
		// Log provider may not be ready yet; fall back to stdlib.
		panic("failed to init app: " + err.Error())
	}
	defer cleanup()

	log := app.Log.Logger
	log.Info("application started",
		zap.String("redis_addr", app.Redis.Config.Address),
	)

	container.HandleSignals(cleanup)

	log.Info("application stopped")
}
